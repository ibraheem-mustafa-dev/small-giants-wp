'use strict';

// GROUND-TRUTH: spec=.claude/plans/media-element-tingly-stallman.md ("Wave 6 —
// media-attr-parity: server-registered schema matches the JS keys") source=file
// evidence=live-read includes/media-element-attrs-register.php:72-180
// (`sgs_register_media_element_attrs`, the `register_block_type_args` filter
// that actually resolves a block's declared `supports.sgs.mediaElements` into
// its live attribute schema) + includes/helpers-media-element.php:43-92
// (`sgs_media_element_attr()` / `sgs_media_element_stored_attr()`, the naming
// pair the filter calls) + includes/media-element-attributes.generated.php
// (the static base->type / atom->bases map both the filter and this rule
// read — generated by scripts/generate-media-attributes.mjs from the JS
// source of truth, already parity-gated by the EXISTING
// `check-media-attributes-parity` gate).
//
// ── WHAT THIS RULE IS FOR ────────────────────────────────────────────────
// `sgs_register_media_element_attrs()` resolves a block's `mediaElements`
// declaration into its live attribute schema AT RUNTIME, on every page load,
// straight from the generated map — so the resolved schema can never drift
// from the generator's OWN output (that agreement is what
// `check-media-attributes-parity`/`test-media-attr-parity.mjs` already gate,
// globally, block-agnostically). This rule asks a DIFFERENT, per-block
// question those two cannot: for THIS block's OWN `mediaElements` + its OWN
// hand-declared `attributes`, does resolution actually work correctly —
// (1) does every atom id it names exist in the generated atom map, and
// (2) where a hand-declared attribute name COLLIDES with what the atom
// system would inject for that same name, does its declared TYPE actually
// match what the atom expects?
//
// Case (2) matters because the filter's own rule is "the block's own
// declaration always wins" (media-element-attrs-register.php:30,152-154) —
// which is correct for preserving a client's stored defaults, but means a
// TYPE mismatch on a shadowed name is invisible to every existing gate: the
// filter silently skips injecting its own (correct) type entry, WordPress
// registers the block's declared (wrong) type instead, and the failure mode
// is D328's silent-coercion-to-default the moment a value of the injected
// shape is ever written — with every existing gate green, because nothing
// else compares a hand-declared attribute's type against what an ADOPTED
// atom expected it to be.
//
// ── THE TWO FINDING KINDS ────────────────────────────────────────────────
//   unknown-atom-id        — a `mediaElements` entry names an atom id absent
//                             from the generated atom map (mirrors the
//                             runtime `_doing_it_wrong()` at
//                             media-element-attrs-register.php:128-137, but
//                             catches it statically, before deploy).
//   shadowed-type-mismatch — the block's own `attributes` declares a name
//                             the atom system would also inject for this
//                             `mediaElements` entry, with a DIFFERENT
//                             `type` than the generated map says that base
//                             carries.
//
// ── WHY THIS SHELLS OUT TO PHP RATHER THAN RE-DERIVING IN JS ─────────────
// `sgs_media_element_stored_attr()` carries a small STORED_AS override table
// (4 names across 2 blocks, per its own docblock — before-after's
// block-level `videoAutoplay*` and decorative-image's legacy `decorMedia`).
// A hand-copied THIRD version of that table in this rule would be a second
// chance for the naming convention to drift out from under a rule meant to
// catch exactly that class of drift. This rule calls the REAL PHP function
// via a single batched `php -r` invocation instead — same shell-out
// convention `scripts/tests/test-media-atom-parity.mjs` already uses to
// call real atom `css()` twins, and the same module-level-cache-once-per-
// scan shape rule 34 already uses for its `check-dead-controls.js
// --dump-json` shell-out (see `loadResolution()` below).
//
// ── EXPECTED POPULATION (stated BEFORE trusting a live run, per
//    rules.json._meta.zeroIsAClaim) ────────────────────────────────────
// `grep -rln '"mediaElements"' src/blocks/*/block.json` (excluding
// `_comment_mediaElements` prose keys) returns exactly TWO blocks today:
// `sgs/media` and `sgs/before-after` — the two fully-migrated reference
// blocks. Both are documented (architecture doc §17) as clean by
// construction. Expected live population: **0 findings**. A non-zero result
// on either reference block, or any result before a Wave 7 surface has
// landed its own `mediaElements` declaration, is a bug in THIS rule, not in
// the framework — re-derive rather than trust.
//
// ── KNOWN BLIND SPOTS (declared, not fixed here) ─────────────────────────
//   - Only checks NAME/TYPE collision, not whether a hand-declared
//     attribute's `default` value is sane for the atom's own vocabulary
//     (e.g. an `object-fit`-shadowing string default outside
//     cover|contain|fill|none|scale-down). That is a narrower, harder
//     question (the vocabulary lives per-atom in registry.js, an ES module
//     this CommonJS rule cannot statically import — see the shell-out note
//     above) left for a future rule if it proves needed.
//   - Tiering correctness (`Tablet`/`Mobile` siblings only injected for
//     bases in the generated `tiered` list) is exercised implicitly by
//     reusing the real PHP resolution rather than re-deriving it, so a bug
//     in the generated `tiered` list itself is NOT this rule's target —
//     that list's OWN generation is already covered by
//     `check-media-attributes-parity`.

const fs = require( 'fs' );
const os = require( 'os' );
const path = require( 'path' );
const { execFileSync } = require( 'child_process' );
const { makeFinding } = require( '../core/finding' );

const PLUGIN_ROOT = path.resolve( __dirname, '..', '..', '..' );
const GENERATED_MAP_FILE = path.join(
	PLUGIN_ROOT,
	'includes',
	'media-element-attributes.generated.php'
);
const HELPERS_FILE = path.join( PLUGIN_ROOT, 'includes', 'helpers-media-element.php' );
const REGISTRY_FILE = path.join(
	PLUGIN_ROOT,
	'src',
	'components',
	'media',
	'atoms',
	'registry.js'
);

// Module-level cache — see rule 34's identical rationale: one `php` child
// process per SCAN (not per block), and the cache holds either the resolved
// value or the caught error so a broken producer only pays the cost once.
let cachedResolution = null;
let cachedError = null;
let cachedReadsMap = null;

/**
 * `reads` (registry.js) is the documented, INTENTIONAL exception list for a
 * name an atom would inject that a block's own declaration deliberately
 * keeps in a legacy shape (e.g. `sgs/media`'s `thumbnail` string, a
 * pre-atom-migration fallback render.php still reads on purpose). A
 * shadowed name documented there is NOT a bug this rule should flag — it IS
 * the class of divergence `reads` exists to record.
 *
 * `registry.js` is an ES module; this rule runs as CommonJS (`require()`
 * cannot load it). Rather than hand-copying `reads` into a second, THIRD
 * table here (exactly the drift risk this rule's own header warns against
 * for the PHP-side STORED_AS table), shell out to `node` once per scan and
 * dynamic-`import()` the real module — the same "call the real thing,
 * never re-derive it" principle `phpResolve()` already applies to
 * `sgs_media_element_stored_attr()`.
 *
 * @return {Object} atomId -> blockSlug -> Set of exempt attribute names.
 */
function loadReadsMap() {
	if ( cachedReadsMap ) return cachedReadsMap;
	const url = 'file:///' + REGISTRY_FILE.split( String.fromCharCode( 92 ) ).join( '/' );
	const body =
		`import(${ JSON.stringify( url ) }).then((m) => {` +
		'const out = {};' +
		'for (const [atomId, atom] of Object.entries(m.MEDIA_ATOMS || {})) {' +
		'out[atomId] = {};' +
		'for (const [slug, names] of Object.entries(atom.reads || {})) {' +
		'out[atomId][slug] = Object.keys(names || {});' +
		'}' +
		'}' +
		'process.stdout.write(JSON.stringify(out));' +
		'process.exit(0);' +
		'}).catch((e) => { process.stderr.write(String(e && e.stack || e)); process.exit(1); });';
	const out = execFileSync( 'node', [ '-e', body ], { encoding: 'utf8' } );
	const parsed = JSON.parse( out );
	const result = {};
	for ( const atomId of Object.keys( parsed ) ) {
		result[ atomId ] = {};
		for ( const slug of Object.keys( parsed[ atomId ] ) ) {
			result[ atomId ][ slug ] = new Set( parsed[ atomId ][ slug ] );
		}
	}
	cachedReadsMap = result;
	return result;
}

/** Is this exact (atomId, blockSlug, attrName) a documented `reads` exception? */
function isDocumentedReadsException( readsMap, atomId, blockSlug, attrName ) {
	const forAtom = readsMap[ atomId ];
	if ( ! forAtom ) return false;
	const forBlock = forAtom[ blockSlug ];
	return !! forBlock && forBlock.has( attrName );
}

/**
 * Batch-resolve, via the REAL PHP functions, everything this rule needs:
 * the generated base->type/atom->bases maps, plus every requested
 * (block, prefix, base) triple's actual stored attribute name.
 *
 * @param {Array<{block:string, prefix:string, base:string}>} requests
 * @return {{generated: Object, storedNames: string[]}}
 */
function phpResolve( requests ) {
	const P = PLUGIN_ROOT.split( String.fromCharCode( 92 ) ).join( '/' );
	// The request list is embedded via a TEMP FILE, not inline in the `-r`
	// argument. A block declaring many `mediaElements` entries (e.g. hero's
	// three, each with several atoms' full base lists across three tiers)
	// pushes the JSON-encoded request array past Windows' command-line length
	// limit — proven live: hero's real requests threw `spawnSync php
	// ENAMETOOLONG` with the inline-argument approach, invisible against the
	// two-block (sgs/media, sgs/before-after) population this rule was first
	// tested against, since neither comes close to the limit alone. A temp
	// file has no such ceiling.
	const tmpFile = path.join(
		os.tmpdir(),
		`sgs-media-attr-parity-requests-${ process.pid }-${ Date.now() }.json`
	);
	fs.writeFileSync( tmpFile, JSON.stringify( requests ), 'utf8' );
	try {
		const body =
			// helpers-media-element.php and the generated attributes file both guard
			// on `defined('ABSPATH') || exit;` — without this, PHP exits silently
			// with EMPTY stdout (no fatal, no stderr), which surfaces downstream as
			// `JSON.parse('')` throwing "Unexpected end of JSON input" — a confusing
			// error one level removed from the real cause. Mirrors the same guard
			// scripts/tests/test-media-atom-parity.mjs already defines for the same
			// reason (its own `boot` string, ~line 156/314).
			`define("ABSPATH", ${ JSON.stringify( P + '/' ) });` +
			'function esc_html($s){return $s;} function esc_html__($s,$d=null){return $s;}' +
			'function _doing_it_wrong($f,$m,$v){}' +
			`require ${ JSON.stringify( HELPERS_FILE.split( String.fromCharCode( 92 ) ).join( '/' ) ) };` +
			`$generated = require ${ JSON.stringify(
				GENERATED_MAP_FILE.split( String.fromCharCode( 92 ) ).join( '/' )
			) };` +
			`$requests = json_decode(file_get_contents(${ JSON.stringify(
				tmpFile.split( String.fromCharCode( 92 ) ).join( '/' )
			) }), true);` +
			'$stored = array_map(function($r){' +
			'return sgs_media_element_stored_attr($r["block"], $r["prefix"], $r["base"]);' +
			'}, $requests ?: array());' +
			'echo json_encode(array("generated"=>$generated, "storedNames"=>array_values($stored)));';
		const out = execFileSync( 'php', [ '-r', body ], { encoding: 'utf8' } );
		return JSON.parse( out );
	} finally {
		try {
			fs.unlinkSync( tmpFile );
		} catch ( e ) {
			// Best-effort cleanup — a leftover temp file in os.tmpdir() is
			// harmless and never read by a later run (the filename embeds
			// pid+timestamp).
		}
	}
}

/**
 * Build the (block, prefix, base) request list for one block's
 * `mediaElements` declaration, against the generated atom map.
 *
 * @return {{requests: Array, unknownAtomIds: string[], tieredBases: string[]}}
 */
function buildRequests( blockSlug, mediaElements, generated ) {
	const atomMap = ( generated && generated.atoms ) || {};
	const tiered = ( generated && generated.tiered ) || [];
	const requests = [];
	const unknownAtomIds = [];

	for ( const element of mediaElements ) {
		const prefix = typeof element.prefix === 'string' ? element.prefix : '';
		const atomIds =
			Array.isArray( element.atoms ) && element.atoms.length
				? element.atoms
				: Object.keys( atomMap );

		// base -> owning atomId (first atom that claims a base wins the label;
		// only used for `reads`-exemption lookup, never for CSS/type resolution).
		const baseOwner = new Map();
		for ( const atomId of atomIds ) {
			if ( ! Object.prototype.hasOwnProperty.call( atomMap, atomId ) ) {
				if ( ! unknownAtomIds.includes( atomId ) ) unknownAtomIds.push( atomId );
				continue;
			}
			( atomMap[ atomId ] || [] ).forEach( ( b ) => {
				if ( ! baseOwner.has( b ) ) baseOwner.set( b, atomId );
			} );
		}

		for ( const [ base, atomId ] of baseOwner ) {
			const tiers = tiered.includes( base ) ? [ '', 'Tablet', 'Mobile' ] : [ '' ];
			for ( const tier of tiers ) {
				requests.push( { block: blockSlug, prefix, base: base + tier, tier, atomId } );
			}
		}
	}

	return { requests };
}

/**
 * Compute, once per scan, every mediaElements-adopting block's resolution
 * result: unknown atom ids, and shadowed-attribute type mismatches.
 *
 * @return {{ok:true, byBlock:Object}|{ok:false, error:string}}
 */
function loadResolution( ctx ) {
	if ( cachedResolution ) return { ok: true, byBlock: cachedResolution };
	if ( cachedError ) return { ok: false, error: cachedError };

	try {
		const byBlock = {};
		const allRequests = [];
		const requestOwners = []; // parallel array: which (blockTail, base) each flat request belongs to

		// ⛔ Walks ctx.blocksDir directly, NOT ctx.roster.entries. Self-test's
		// context (core/selftest.js:58) always sets `roster: { entries: [] }` —
		// per-block fixtures are discovered by scanning the copied fixture
		// directory instead — so a discovery loop keyed on roster.entries would
		// silently see zero blocks in every self-test run, and no mustFlag case
		// could ever fire. Reading the directory + each block.json's own `name`
		// field (authoritative, works identically for a real block or a
		// fixture) matches exactly how selftest.js discovers per-block fixtures.
		let tails;
		try {
			tails = fs
				.readdirSync( ctx.blocksDir, { withFileTypes: true } )
				.filter( ( d ) => d.isDirectory() )
				.map( ( d ) => d.name );
		} catch ( e ) {
			tails = [];
		}

		for ( const tail of tails ) {
			const blockJsonFile = path.join( ctx.blocksDir, tail, 'block.json' );
			const parsed = ctx.json( blockJsonFile );
			if ( ! parsed.ok ) continue;
			const data = parsed.data || {};
			const mediaElements =
				data.supports && data.supports.sgs && Array.isArray( data.supports.sgs.mediaElements )
					? data.supports.sgs.mediaElements
					: null;
			if ( ! mediaElements || ! mediaElements.length ) continue;

			byBlock[ tail ] = {
				slug: typeof data.name === 'string' && data.name ? data.name : `sgs/${ tail }`,
				declaredAttributes: data.attributes || {},
				unknownAtomIds: [],
				requestBases: [], // filled below once the generated map is known
			};
		}

		if ( ! Object.keys( byBlock ).length ) {
			cachedResolution = byBlock;
			return { ok: true, byBlock };
		}

		// First shell-out: fetch the generated map alone (empty request list),
		// so buildRequests() can resolve real atom ids before the second,
		// full batched call.
		const first = phpResolve( [] );
		const generated = first.generated || {};

		for ( const tail of Object.keys( byBlock ) ) {
			const blockJsonFile = path.join( ctx.blocksDir, tail, 'block.json' );
			const parsed = ctx.json( blockJsonFile );
			const data = ( parsed.ok && parsed.data ) || {};
			const mediaElements = data.supports.sgs.mediaElements;
			const { requests } = buildRequests( byBlock[ tail ].slug, mediaElements, generated );

			// Re-detect unknown atom ids against the real generated map (buildRequests
			// already did this, but call again explicitly here for clarity/ownership).
			const atomMap = generated.atoms || {};
			const unknown = new Set();
			mediaElements.forEach( ( el ) => {
				( Array.isArray( el.atoms ) ? el.atoms : [] ).forEach( ( id ) => {
					if ( ! Object.prototype.hasOwnProperty.call( atomMap, id ) ) unknown.add( id );
				} );
			} );
			byBlock[ tail ].unknownAtomIds = [ ...unknown ];

			requests.forEach( ( r ) => {
				allRequests.push( r );
				requestOwners.push( { tail, base: r.base, atomId: r.atomId } );
			} );
		}

		const second = allRequests.length ? phpResolve( allRequests ) : { storedNames: [] };
		const storedNames = second.storedNames || [];
		const basesTypeMap = generated.bases || {};
		const readsMap = loadReadsMap();

		storedNames.forEach( ( storedName, i ) => {
			const owner = requestOwners[ i ];
			if ( ! owner ) return;
			const info = byBlock[ owner.tail ];
			const declared = info.declaredAttributes[ storedName ];
			if ( ! declared ) return; // not shadowed — the atom system owns this name cleanly

			// A documented `reads` exception (registry.js) means this shadow is
			// INTENTIONAL — a known legacy shape the block deliberately keeps,
			// not a drift to flag.
			if ( isDocumentedReadsException( readsMap, owner.atomId, info.slug, storedName ) ) {
				return;
			}

			// Strip the tier suffix to look up the base's declared type.
			const baseWithoutTier = owner.base.replace( /(Tablet|Mobile)$/, '' );
			const expectedType = basesTypeMap[ baseWithoutTier ];
			if ( ! expectedType ) return;

			const declaredType = Array.isArray( declared.type )
				? declared.type
				: [ declared.type ];
			if ( ! declaredType.includes( expectedType ) ) {
				info.shadowMismatches = info.shadowMismatches || [];
				info.shadowMismatches.push( {
					attrName: storedName,
					expectedType,
					declaredType: declared.type,
				} );
			}
		} );

		cachedResolution = byBlock;
		return { ok: true, byBlock };
	} catch ( e ) {
		cachedError = e.message || String( e );
		return { ok: false, error: cachedError };
	}
}

module.exports = {
	id: '38-media-attr-parity',
	checklistItem: null,
	title:
		'A block\'s `supports.sgs.mediaElements` declaration names an unknown atom id, or a ' +
		'hand-declared attribute silently shadows an atom-injected one with a mismatched type',
	scope: 'per-block',
	needs: [ 'json:block.json' ],
	run( ctx, block ) {
		const ruleId = this.id;
		const resolution = loadResolution( ctx );
		if ( ! resolution.ok ) {
			return [
				makeFinding( {
					rule: ruleId,
					block: block.slug,
					file: path.join( ctx.blocksDir, block.tail, 'block.json' ),
					severity: 'error',
					kind: 'resolution-producer-failed',
					detail:
						'Could not resolve this block\'s media-element attribute schema via PHP: ' +
						resolution.error,
					fix:
						'Run `php -r` manually against includes/helpers-media-element.php and ' +
						'includes/media-element-attributes.generated.php to find the parse/require error.',
					keyParts: [ 'resolution-producer-failed' ],
				} ),
			];
		}

		const info = resolution.byBlock[ block.tail ];
		if ( ! info ) return []; // this block does not declare mediaElements

		const findings = [];
		const blockJsonFile = path.join( ctx.blocksDir, block.tail, 'block.json' );

		for ( const atomId of info.unknownAtomIds ) {
			findings.push(
				makeFinding( {
					rule: ruleId,
					block: block.slug,
					file: blockJsonFile,
					severity: 'error',
					kind: 'unknown-atom-id',
					detail:
						`\`supports.sgs.mediaElements\` names an atom id "${ atomId }" that does not exist ` +
						'in the generated atom map (includes/media-element-attributes.generated.php). ' +
						'At runtime this silently injects fewer attributes than declared — indistinguishable ' +
						'from the block simply lacking those controls.',
					fix:
						'Fix the typo, or if this is a genuinely new atom, add it to ' +
						'src/components/media/atoms/registry.js and regenerate via ' +
						'`node scripts/generate-media-attributes.mjs`.',
					keyParts: [ 'unknown-atom-id', atomId ],
				} )
			);
		}

		for ( const mismatch of info.shadowMismatches || [] ) {
			findings.push(
				makeFinding( {
					rule: ruleId,
					block: block.slug,
					file: blockJsonFile,
					severity: 'error',
					kind: 'shadowed-type-mismatch',
					detail:
						`This block's own \`attributes.${ mismatch.attrName }\` declares type ` +
						`${ JSON.stringify( mismatch.declaredType ) }, but the adopted media atom expects ` +
						`type ${ JSON.stringify( mismatch.expectedType ) } for this name. Because a block's ` +
						'own declaration always wins over the atom-injected one, this attribute never gets ' +
						'the type the atom system expects — WordPress silently coerces a mismatched value ' +
						'back to its default the moment one is written (D328).',
					fix:
						'Either remove this block\'s own duplicate declaration of ' +
						`\`${ mismatch.attrName }\` (letting the atom system inject the correct type), or, ` +
						'if this name is deliberately NOT the atom-owned one, rename the atom-facing control ' +
						'to a different base so the two stop colliding.',
					keyParts: [ 'shadowed-type-mismatch', mismatch.attrName ],
				} )
			);
		}

		return findings;
	},
	selfTest: {
		fixture: 'fixtures/38-media-attr-parity',
		mustFlag: [ 'unknown-atom-id-block', 'shadowed-type-mismatch-block' ],
		mustNotFlag: [ 'sgs-media-silent', 'before-after-silent', 'not-adopted-silent' ],
	},
};
