/**
 * Writes the media atoms' attributes into each adopting block's committed
 * `block.json`, and the framework-database override entries that describe them.
 *
 * Pure functions over text: `scripts/generate-media-attributes.mjs` reads the
 * files, calls these, and either writes the results or (with `--check`)
 * compares them with what is on disk.
 *
 * Only entries that declare `kinds` are written (Spec 49 §8.3), and they are written in §8's names: for each such
 * `supports.sgs.mediaElements` entry, one attribute per adopted setting of the atoms it names (all adopted atoms when
 * `atoms` is omitted), named `{prefix}{Base}`. A responsive setting is one `object` attribute holding the
 * `{desktop,tablet,mobile}` value, never Tablet and Mobile siblings. Any name the block already declares itself (its type must match the setting's), or an
 * earlier entry already produced, is skipped; every such name is reported in one run (a type mismatch throws naming all
 * of them, a same-type one is listed in `report.kept`).
 *
 * Generated attributes carry `"_generated": "media-atoms"`, sit on one line
 * each at the end of `attributes`, and are rewritten from scratch on every run,
 * so editing the registry and re-running is the only way to change them.
 */

import fs from 'fs';
import path from 'path';

export const GENERATED_MARK = 'media-atoms';
const MARK_RE = /"_generated"\s*:\s*"media-atoms"/;
export const OVERRIDE_REASON =
	'generated by scripts/generate-media-attributes.mjs from the media atom registry; change the atom setting and re-run, never this line';

/**
 * Every `block.json` under a directory.
 *
 * @param {string} dir Directory to walk.
 * @return {string[]} Absolute file paths, sorted.
 */
export function findBlockJsons( dir ) {
	const out = [];
	const walk = ( d ) => {
		for ( const entry of fs.readdirSync( d, { withFileTypes: true } ) ) {
			const full = path.join( d, entry.name );
			if ( entry.isDirectory() ) {
				walk( full );
			} else if ( entry.name === 'block.json' ) {
				out.push( full );
			}
		}
	};
	walk( dir );
	return out.sort();
}

/**
 * The attributes a block's `mediaElements` declaration generates.
 *
 * @param {Object}   block     Parsed block.json.
 * @param {Object}   env       { attrName, adoptedSettings }: the §8 name of a prefix and base, and the adopted settings
 *                             of an entry.

 * @param {Object}   ownDefs   The attributes the block declares itself, name to definition. A name the generator would
 *                             also write must carry the same type, or this throws naming every such attribute.
 * @param {{kept: string[]}} [report] Receives `block attribute` for each own attribute kept because its type matches.
 * @return {Array<{name:string, def:Object, base:string, tier:string, prefix:string}>} In injection order.
 */
export function generatedAttributes( block, env, ownDefs, report ) {
	// Only an entry that declares `kinds` has adopted the new slot declaration
	// (Spec 49 §8.3); an entry without it keeps its attributes from the
	// registration filter.
	const declared = block?.supports?.sgs?.mediaElements;
	const elements = Array.isArray( declared )
		? declared.filter( ( element ) => Array.isArray( element?.kinds ) )
		: [];
	if ( ! elements.length ) {
		return [];
	}
	const own = ownDefs || {};
	const seen = new Set();
	const out = [];
	const clashes = [];
	for ( const element of elements ) {
		const prefix = element?.prefix ? String( element.prefix ) : '';
		for ( const setting of env.adoptedSettings( element ) ) {
			const name = env.attrName( prefix, setting.base );
			if ( seen.has( name ) ) {
				continue;
			}
			if ( Object.prototype.hasOwnProperty.call( own, name ) ) {
				const wanted = setting.responsive ? 'object' : setting.type;
				const declaredType = own[ name ]?.type;
				const types = Array.isArray( declaredType ) ? declaredType : [ declaredType ];
				if ( ! types.includes( wanted ) ) {
					clashes.push(
						`${ block?.name }: attribute "${ name }" is declared as ${ JSON.stringify( declaredType ) } but the media atom setting needs "${ wanted }"`
					);
				} else if ( report ) {
					report.kept.push( `${ block?.name } ${ name }` );
				}
				continue;
			}
			seen.add( name );
			out.push( {
				name,
				def: setting.responsive || 'array' !== setting.type
					? { type: setting.responsive ? 'object' : setting.type, _generated: GENERATED_MARK }
					: { type: 'array', default: [], _generated: GENERATED_MARK },
				base: setting.base,
				tier: '',
				prefix,
				setting,
			} );
		}
	}
	if ( clashes.length ) {
		throw new Error( `${ clashes.join( '; ' ) }; fix the block.json declaration or the atom setting` );
	}
	return out;
}

/**
 * Locate the top-level `attributes` object in block.json text.
 *
 * @param {string} text block.json source.
 * @return {{open:number, close:number}|null} Index of its `{` and its `}`.
 */
export function attributesRange( text ) {
	let depth = 0;
	let open = -1;
	let i = 0;
	let lastKey = null;
	while ( i < text.length ) {
		const ch = text[ i ];
		if ( ch === '"' ) {
			let j = i + 1;
			while ( text[ j ] !== '"' ) {
				j += text[ j ] === '\\' ? 2 : 1;
			}
			const str = text.slice( i + 1, j );
			if ( depth === 1 && open === -1 ) {
				lastKey = str;
			}
			i = j + 1;
			continue;
		}
		if ( ch === '{' || ch === '[' ) {
			depth += 1;
			if ( open === -1 && depth === 2 && ch === '{' && lastKey === 'attributes' ) {
				open = i;
			}
		} else if ( ch === '}' || ch === ']' ) {
			if ( open !== -1 && depth === 2 && ch === '}' ) {
				return { open, close: i };
			}
			depth -= 1;
		}
		i += 1;
	}
	return null;
}

const lineFor = ( indent, a ) =>
	`${ indent }${ JSON.stringify( a.name ) }: ${ JSON.stringify( a.def ) }`;

/**
 * Rewrite block.json text so its generated attributes equal `attrs`.
 *
 * @param {string} text  Current block.json source.
 * @param {Array}  attrs Output of generatedAttributes().
 * @return {string} New source (identical to `text` when nothing changes).
 */
export function applyGeneratedAttributes( text, attrs ) {
	const range = attributesRange( text );
	if ( ! range ) {
		if ( attrs.length ) {
			throw new Error( 'block.json has no top-level "attributes" object to write into' );
		}
		return text;
	}
	const eol = text.includes( '\r\n' ) ? '\r\n' : '\n';
	const inner = text.slice( range.open + 1, range.close );
	const lines = inner.split( '\n' );
	const kept = lines.filter( ( l ) => ! MARK_RE.test( l ) );
	if ( kept.length === lines.length && ! attrs.length ) {
		return text;
	}
	// The line holding the closing brace begins with its indentation.
	const closeIndent = /([ \t]*)$/.exec( inner )?.[ 1 ] ?? '';
	const before = text.slice( 0, text.lastIndexOf( '\n', range.open ) + 1 );
	const openLineIndent = /^[ \t]*/.exec( text.slice( before.length ) )[ 0 ];
	const indent = openLineIndent + '\t';
	let body = kept.join( '\n' ).replace( /\s+$/, '' ).replace( /,$/, '' );
	if ( attrs.length ) {
		body += ( body.trim() ? ',' : '' ) + eol + attrs.map( ( a ) => lineFor( indent, a ) ).join( ',' + eol );
	}
	return text.slice( 0, range.open + 1 ) + body + eol + closeIndent + text.slice( range.close );
}

/** Compact JSON with `": "` and `", "` separators, the override file's single-line style. */
function spaced( value ) {
	if ( Array.isArray( value ) ) {
		return '[' + value.map( spaced ).join( ', ' ) + ']';
	}
	if ( value && typeof value === 'object' ) {
		return '{' + Object.keys( value ).map( ( k ) => `${ JSON.stringify( k ) }: ${ spaced( value[ k ] ) }` ).join( ', ' ) + '}';
	}
	return JSON.stringify( value );
}

/**
 * The override entry describing one generated attribute.
 *
 * Carries only what the seeder cannot derive: the role, the tier shape and the Alt's
 * companion. It never states `css_property`, `css_element`, `css_layer` or
 * `css_state`: check #8 reads a `css_property` key as the pair (property, layer) and the
 * seeder derives a layer (for example GRID_AREA on the hero's split media) that an entry
 * leaving it out would contradict. The paint node and property live in the registry's
 * C1 settings, which the Stage B emitters read.
 *
 * @param {string} slug  Block slug.
 * @param {Object} attr  One generatedAttributes() item.
 * @param {Object} setting The adopted C1 entry for the attribute's base.
 * @param {string} companion Stored name of the Url attribute for an Alt, else ''.
 * @param {boolean} tiered Whether the attribute holds the responsive object.
 * @return {Object} { slug, attr, fields, _reason }.
 */
export function overrideEntry( slug, attr, setting, companion, tiered ) {
	const fields = { role: setting.role };
	if ( tiered ) {
		fields.tier_shape = 'tier_object';
	}
	if ( companion ) {
		fields.alt_companion_attr = companion;
	}
	return { slug, attr: attr.name, fields, _reason: OVERRIDE_REASON };
}

/**
 * Rewrite the override file so its generated entries equal `entries`.
 *
 * With `onlySlug`, generated lines for other blocks are kept as they are.
 *
 * @param {string}   text      Current attr-classification-overrides.json source.
 * @param {Object[]} entries   overrideEntry() results.
 * @param {string}   [onlySlug] Restrict the rewrite to one block.
 * @return {string} New source.
 */
export function applyOverrideEntries( text, entries, onlySlug ) {
	let cut = text.lastIndexOf( '\n\t]' );
	if ( cut === -1 ) {
		throw new Error( 'override file has no closing entries array' );
	}
	const eol = text[ cut - 1 ] === '\r' ? '\r\n' : '\n';
	if ( eol === '\r\n' ) {
		cut -= 1;
	}
	const slugOf = ( l ) => /"slug":\s*"([^"]+)"/.exec( l )?.[ 1 ];
	const lines = text.slice( 0, cut ).split( '\n' );
	const keptOthers = [];
	const rest = lines.filter( ( l ) => {
		if ( ! l.includes( OVERRIDE_REASON ) ) {
			return true;
		}
		if ( onlySlug && slugOf( l ) !== onlySlug ) {
			keptOthers.push( l.trim().replace( /,$/, '' ) );
		}
		return false;
	} );
	const generated = [
		...keptOthers,
		...entries.map( ( e ) => spaced( e ) ),
	];
	let head = rest.join( '\n' ).replace( /\s+$/, '' ).replace( /,$/, '' );
	if ( generated.length ) {
		head += ',' + eol + generated.map( ( l ) => '\t\t' + l ).join( ',' + eol );
	}
	return head + text.slice( cut );
}

/**
 * (slug, attr) keys that already have a hand-written override entry.
 *
 * @param {string} text Override file source.
 * @return {Set<string>} `slug|attr` keys of entries that are not generated.
 */
export function handWrittenOverrideKeys( text ) {
	const data = JSON.parse( text );
	const out = new Set();
	for ( const e of data.entries ) {
		if ( e._reason !== OVERRIDE_REASON ) {
			out.add( `${ e.slug }|${ e.attr }` );
		}
	}
	return out;
}
