/**
 * Builds `schemas/media-slot.schema.json` (Spec 49 FR-49-34) from the adopted settings and the value shapes in
 * `scripts/data/media-slot-properties.json`.
 *
 * A slot document is keyed by Spec 49 §8 base in lower camel case (`source`, `fit`, `borderWidth`); a block's real
 * attribute name adds the slot prefix. A responsive setting is one `{desktop,tablet,mobile}` object whose tiers hold the
 * base's value; any other setting holds the value directly. Every `$defs` entry is also the `properties` node the
 * Stage B generator copies onto the attribute, so `scripts/wp-build-page.js` and the cloner read one shape.
 */

export const TIERS = [ 'desktop', 'tablet', 'mobile' ];

/** @param {string} base Spec 49 §8 base, for example `BorderWidth`. @return {string} `borderWidth`. */
export const slotKey = ( base ) => base.charAt( 0 ).toLowerCase() + base.slice( 1 );

/**
 * The `properties` node of one base's attribute.
 *
 * @param {Object}  value      The base's value shape (JSON Schema subset).
 * @param {boolean} responsive Whether the setting is per device.
 * @return {Object} The node.
 */
export function attributeNode( value, responsive ) {
	if ( ! responsive ) {
		return value;
	}
	const properties = {};
	for ( const tier of TIERS ) {
		properties[ tier ] = value;
	}
	return { type: 'object', additionalProperties: false, properties };
}

/**
 * Build the schema.
 *
 * @param {Array<{base:string,type:string,responsive:boolean,role:string}>} settings Adopted settings.
 * @param {Object} shapes Base to value shape.
 * @return {Object} The schema.
 */
export function buildSchema( settings, shapes ) {
	const bases = new Map();
	for ( const s of settings ) {
		if ( ! bases.has( s.base ) ) {
			bases.set( s.base, s );
		}
	}
	const missing = [ ...bases.keys() ].filter( ( b ) => ! shapes[ b ] );
	const extra = Object.keys( shapes ).filter( ( b ) => ! bases.has( b ) );
	if ( missing.length || extra.length ) {
		throw new Error(
			`media-slot-properties.json and the adopted settings disagree: no shape for [${ missing.join( ', ' ) }]; shape for a base nothing adopts [${ extra.join( ', ' ) }]`
		);
	}
	const defs = {};
	const properties = {};
	for ( const base of [ ...bases.keys() ].sort() ) {
		const s = bases.get( base );
		const shape = shapes[ base ];
		if ( s.type !== shape.type && ! ( s.responsive && 'object' === s.type ) ) {
			throw new Error( `${ base }: the adopted setting is "${ s.type }" but its shape is "${ shape.type }"` );
		}
		defs[ base ] = {
			...attributeNode( shape, !! s.responsive ),
			'x-sgs-base': base,
			'x-sgs-role': s.role,
			'x-sgs-responsive': !! s.responsive,
		};
		properties[ slotKey( base ) ] = { $ref: `#/$defs/${ base }` };
	}
	return {
		$schema: 'https://json-schema.org/draft/2020-12/schema',
		$id: 'https://sgs.local/schemas/media-slot.schema.json',
		title: 'SGS media slot (Spec 49 FR-49-34)',
		description: 'One slot\'s settings in Spec 49 section 8 names (lower camel case, no slot prefix). Unknown keys and shapes are refused. Generated by scripts/generate-media-slot-schema.mjs; do not edit.',
		type: 'object',
		additionalProperties: false,
		properties,
		$defs: defs,
	};
}
