/**
 * generate-commerce-look-table.js
 *
 * The Cart and Checkout look table (includes/woocommerce/commerce-look/selectors.json: `columns` and each row's
 * `columns`) defines settings by row prefix plus column suffix. The repo's other generators read attribute
 * definitions as literals (scripts/generate-extension-attributes.js scans `sgsName: { type }`, and the extension
 * roster lists every attribute), so this script writes those literals from the table:
 *
 *   - src/blocks/extensions/commerce-look/attributes-table.generated.js  one `sgsName: { type: '...' },` line each
 *   - src/blocks/extensions/extension-roster.json                        the commerceLook rows marked "gen": "table"
 *
 * Both are replaced whole on every run, so a table edit cannot leave a stale line. A table setting whose name
 * repeats an attribute written by hand in attributes.js stops the run.
 *
 * Usage:
 *   node scripts/generate-commerce-look-table.js           # write both files
 *   node scripts/generate-commerce-look-table.js --check   # exit 1 if either is stale or a name repeats
 *   require('./generate-commerce-look-table').tableAttributes() -> [{ name, type, row, column, css, role, element }]
 */

'use strict';

const fs = require( 'fs' );
const path = require( 'path' );

const ROOT = path.join( __dirname, '..' );
const TABLE_FILE = path.join( ROOT, 'includes', 'woocommerce', 'commerce-look', 'selectors.json' );
const OUT_FILE = path.join( ROOT, 'src', 'blocks', 'extensions', 'commerce-look', 'attributes-table.generated.js' );
const HAND_FILE = path.join( ROOT, 'src', 'blocks', 'extensions', 'commerce-look', 'attributes.js' );
const ROSTER_FILE = path.join( ROOT, 'src', 'blocks', 'extensions', 'extension-roster.json' );
const MARK = '"gen": "table"';

const TEXT_CSS = {
	FontSize: 'font-size',
	FontSizeUnit: 'font-size',
	FontSizeTablet: 'font-size',
	FontSizeMobile: 'font-size',
	FontFamily: 'font-family',
	FontWeight: 'font-weight',
	FontStyle: 'font-style',
	LineHeight: 'line-height',
	LineHeightUnit: 'line-height',
	LetterSpacing: 'letter-spacing',
	LetterSpacingUnit: 'letter-spacing',
	TextTransform: 'text-transform',
	TextDecoration: 'text-decoration',
	TextAlign: 'text-align',
};

/** Row prefix: the row's own `prefix`, else `sgs` plus the row id in PascalCase (mirrors table.php). */
function rowPrefix( id, row ) {
	if ( row.prefix ) {
		return row.prefix;
	}
	return 'sgs' + id.split( '_' ).map( ( p ) => p.charAt( 0 ).toUpperCase() + p.slice( 1 ) ).join( '' );
}

function readTable() {
	return JSON.parse( fs.readFileSync( TABLE_FILE, 'utf8' ) );
}

/** Every setting the table defines, in row then column order. */
function tableAttributes( table = readTable() ) {
	const out = [];
	for ( const [ id, row ] of Object.entries( table.rows ) ) {
		for ( const column of row.columns || [] ) {
			const def = table.columns[ column ];
			if ( ! def ) {
				throw new Error( `Row ${ id } names an unknown column "${ column }".` );
			}
			for ( const [ index, [ suffix, type ] ] of def.attrs.entries() ) {
				// One CSS slot per property: a unit, a tablet or mobile size and a shadow colour carry no css_property.
				const secondary = /(Unit|Tablet|Mobile)$/.test( suffix ) || ( 'text' !== def.kind && index > 0 );
				out.push( {
					name: rowPrefix( id, row ) + suffix,
					type,
					row: id,
					column,
					css: secondary ? '' : 'text' === def.kind ? TEXT_CSS[ suffix ] || def.css : def.css,
					role: def.role,
					element: id.replace( /_/g, '-' ),
				} );
			}
		}
	}
	return out;
}

/** Attribute names written by hand in attributes.js. */
function handWritten() {
	const src = fs.readFileSync( HAND_FILE, 'utf8' );
	return [ ...src.matchAll( /^\s*(sgs[A-Za-z0-9]*)\s*:\s*\{/gm ) ].map( ( m ) => m[ 1 ] );
}

/** Problems that stop generation: a repeated name, or a name two table cells share. */
function problems( attrs ) {
	const hand = new Set( handWritten() );
	const seen = new Set();
	const bad = [];
	for ( const a of attrs ) {
		if ( hand.has( a.name ) ) {
			bad.push( `${ a.name } (row ${ a.row }, column ${ a.column }) repeats an attribute written by hand in attributes.js` );
		}
		if ( seen.has( a.name ) ) {
			bad.push( `${ a.name } (row ${ a.row }, column ${ a.column }) is defined twice by the table` );
		}
		seen.add( a.name );
	}
	return bad;
}

function renderJs( attrs ) {
	const lines = [];
	lines.push( '/**' );
	lines.push( ' * AUTO-GENERATED by scripts/generate-commerce-look-table.js from includes/woocommerce/commerce-look/selectors.json: DO NOT EDIT BY HAND.' );
	lines.push( ' * One literal line per attribute so scripts/generate-extension-attributes.js and check-extension-roster.js read it.' );
	lines.push( ' */' );
	lines.push( 'export const COMMERCE_LOOK_TABLE_ATTRIBUTES = {' );
	for ( const a of attrs ) {
		lines.push( `\t${ a.name }: { type: '${ a.type }' },` );
	}
	lines.push( '};' );
	lines.push( '' );
	return lines.join( '\n' );
}

function rosterLine( a ) {
	const bits = [ `"type": "${ a.type }"` ];
	if ( 'object' === a.type ) {
		bits.push( '"tier_shape": "tier_object"', '"is_responsive": 1' );
	}
	bits.push( `"role": "${ a.role }"` );
	if ( a.css ) {
		bits.push( `"css_property": "${ a.css }"`, `"css_element": "${ a.element }"` );
	}
	bits.push( MARK );
	return `\t\t\t\t"${ a.name }": { ${ bits.join( ', ' ) } },`;
}

function renderRoster( attrs ) {
	const eol = fs.readFileSync( ROSTER_FILE, 'utf8' ).includes( '\r\n' ) ? '\r\n' : '\n';
	const kept = fs.readFileSync( ROSTER_FILE, 'utf8' ).split( /\r?\n/ ).filter( ( l ) => ! l.includes( MARK ) );
	const at = kept.findIndex( ( l ) => l.includes( '"sgsCheckoutStrings"' ) );
	if ( at < 0 ) {
		throw new Error( 'extension-roster.json: the commerceLook "sgsCheckoutStrings" line (the insertion point) is missing.' );
	}
	// Insert above the blank line that precedes sgsCheckoutStrings.
	const insert = '' === kept[ at - 1 ].trim() ? at - 1 : at;
	kept.splice( insert, 0, ...attrs.map( rosterLine ) );
	return kept.join( eol );
}

function main() {
	const check = process.argv.includes( '--check' );
	const attrs = tableAttributes();
	const bad = problems( attrs );
	if ( bad.length ) {
		process.stderr.write( '[generate-commerce-look-table] REFUSED:\n  ' + bad.join( '\n  ' ) + '\n' );
		process.exit( 1 );
	}
	const js = renderJs( attrs );
	const roster = renderRoster( attrs );
	const currentJs = fs.existsSync( OUT_FILE ) ? fs.readFileSync( OUT_FILE, 'utf8' ) : '';
	const currentRoster = fs.readFileSync( ROSTER_FILE, 'utf8' );
	if ( check ) {
		const stale = [];
		if ( currentJs !== js ) {
			stale.push( path.relative( ROOT, OUT_FILE ) );
		}
		if ( currentRoster !== roster ) {
			stale.push( path.relative( ROOT, ROSTER_FILE ) );
		}
		if ( stale.length ) {
			process.stderr.write( `[generate-commerce-look-table] STALE: ${ stale.join( ', ' ) }. Run: node scripts/generate-commerce-look-table.js\n` );
			process.exit( 1 );
		}
		process.stdout.write( `[generate-commerce-look-table] OK: ${ attrs.length } table settings, files current.\n` );
		return;
	}
	fs.writeFileSync( OUT_FILE, js );
	fs.writeFileSync( ROSTER_FILE, roster );
	process.stdout.write( `[generate-commerce-look-table] wrote ${ attrs.length } table settings.\n` );
}

if ( require.main === module ) {
	main();
}

module.exports = { tableAttributes, handWritten, problems, rowPrefix, renderJs, renderRoster };
