/**
 * Open a form field wrapper div.
 *
 * When conditionalField is set, the wrapper receives data-conditional-* attributes
 * so that view.js can show or hide the field based on another field's value.
 * Hidden-by-default fields also receive the sgs-form-field--hidden CSS class so
 * they are invisible before JavaScript initialises.
 *
 * Calls get_block_wrapper_attributes() so this div — the TRUE outer element of
 * every field-block type — carries the block's WP identity class
 * (wp-block-sgs-form-field-*). Before this (2026-08-30, form-field-tiles
 * border-roundtrip fix), no form-field-* block's outer wrapper ever called
 * get_block_wrapper_attributes() anywhere, so the identity class either never
 * rendered at all, or (form-field-tiles only) landed on an INNER div instead —
 * a different DOM node from the one carrying the block's own scoped/private
 * CSS. Every sibling field.json here declares anchor:false and no other
 * supports classes/styles beyond the identity class itself (verified against
 * each block.json before this change), so the only observable effect is that
 * identity class appearing on this div. form-field-file additionally declares
 * "interactivity": true — but get_block_wrapper_attributes() does NOT emit a
 * data-wp-interactive attribute; that directive is authored in markup, not
 * auto-generated by this core function. Live-measured on the rendered
 * form-field-file output after this change: data-wp-interactive is ABSENT.
 * Any interactivity wiring for that block still has to be authored explicitly
 * elsewhere in its own render.php/view.js, same as before this fix.
 *
 * ⚠ This call now runs WP's block-supports serialiser for every field block.
 * That is safe today only because no sibling field.json declares a WP
 * styling support (color/spacing/border) without __experimentalSkipSerialization
 * — form-field-tiles is the one exception here and it DOES skip-serialise. If
 * a future field block enables a styling support without skip-serialisation,
 * this function will silently start emitting an inline style= attribute — a
 * Spec 32 (no-inline-styling) violation the static audit-inline-styling.js
 * gate is unlikely to trace back to this shared helper. Check block.json for
 * __experimentalSkipSerialization before adding any styling support here.
 *
 * @param array  $attributes Block attributes.
 * @param string $type       Field type (text, email, textarea, select, etc.).
 * @param string $extra_class Additional CSS class (optional).
 * @return string Opening div tag.
 */
function field_open( array $attributes, string $type, string $extra_class = '' ): string {
	$width             = $attributes['width'] ?? 'full';
	$conditional_field = $attributes['conditionalField'] ?? '';

	$classes = array(
		'sgs-form-field',
		'sgs-form-field--' . esc_attr( $type ),
		'sgs-form-field--' . esc_attr( $width ),
	);

	// A field with no visible label (none set, or labelStyle 'hidden') has no
	// floating label to make room for: style.css drops the label space and shows
	// the placeholder for this modifier.
	if ( '' === trim( (string) ( $attributes['label'] ?? '' ) ) || 'hidden' === ( $attributes['labelStyle'] ?? 'visible' ) ) {
		$classes[] = 'sgs-form-field--no-label';
	}

	// floatingLabel off (Spec 04 FR-4-4): the label stays above the box instead of floating
	// inside it. Absent or true keeps the default floating label.
	if ( array_key_exists( 'floatingLabel', $attributes ) && false === $attributes['floatingLabel'] ) {
		$classes[] = 'sgs-form-field--static-label';
	}

	if ( ! empty( $extra_class ) ) {
		$classes[] = esc_attr( $extra_class );
	}

	// Fields with conditional logic start hidden; view.js evaluates and shows them.
	if ( ! empty( $conditional_field ) ) {
		$classes[] = 'sgs-form-field--hidden';
	}

	$data_attrs = '';

	if ( ! empty( $conditional_field ) ) {
		$operator = $attributes['conditionalOperator'] ?? 'equals';
		$value    = $attributes['conditionalValue'] ?? '';

		$data_attrs = sprintf(
			' data-conditional-field="%s" data-conditional-operator="%s" data-conditional-value="%s"',
			esc_attr( $conditional_field ),
			esc_attr( $operator ),
			esc_attr( $value )
		);
	}

	$wrapper_attributes = get_block_wrapper_attributes(
		array(
			'class' => implode( ' ', $classes ),
		)
	);

	return sprintf(
		'<div %s%s>',
		$wrapper_attributes,
		$data_attrs
	);
}

/**
 * Render a field label.
 *
 * @param string $field_id   Field identifier (from field_id()).
 * @param array  $attributes Block attributes.
 * @return string Label HTML (empty if no label).
 */
function field_label( string $field_id, array $attributes ): string {
	$label = $attributes['label'] ?? '';

	if ( empty( $label ) ) {
		return '';
	}

	$required = ! empty( $attributes['required'] );
	// labelStyle 'hidden': read by screen readers only (the field's headings,
	// placeholder or panel text say what it is for).
	$hidden = 'hidden' === ( $attributes['labelStyle'] ?? 'visible' );

	return sprintf(
		'<label for="%s" class="sgs-form-field__label%s">%s%s</label>',
		esc_attr( $field_id ),
		$hidden ? ' sgs-sr-only' : '',
		esc_html( $label ),
		$required ? ' <span class="sgs-form-field__required" aria-hidden="true">*</span><span class="sgs-sr-only">(required)</span>' : ''
	);
}

/**
 * Render a field's visual table headings: a short column heading above the
 * box ("SPH") and a row heading to its left ("R"). Visual only (aria-hidden):
 * the label stays the accessible name ("Right SPH").
 *
 * @param array $attributes Block attributes (columnHeading, rowHeading).
 * @return string Headings HTML (empty if neither is set).
 */
function field_headings( array $attributes ): string {
	$out = '';
	foreach ( array(
		'columnHeading' => 'sgs-form-field__column-heading',
		'rowHeading'    => 'sgs-form-field__row-heading',
	) as $key => $class ) {
		$text = trim( (string) ( $attributes[ $key ] ?? '' ) );
		if ( '' !== $text ) {
			$out .= '<span class="' . $class . '" aria-hidden="true">' . esc_html( $text ) . '</span>';
		}
	}
	return $out;
}

/**
 * Render field help text.
 *
 * @param string $field_id   Field identifier (from field_id()).
 * @param array  $attributes Block attributes.
 * @return string Help text HTML (empty if no help text).
 */
function field_help( string $field_id, array $attributes ): string {
	$help = $attributes['helpText'] ?? '';

	if ( empty( $help ) ) {
		return '';
	}

	return sprintf(
		'<p id="%s-help" class="sgs-form-field__help">%s</p>',
		esc_attr( $field_id ),
		esc_html( $help )
	);
}

/**
 * Close field wrapper div.
 *
 * @return string Closing div tag.
 */
function field_close(): string {
	return '</div>';
}

/**
 * Generate field ID from field name.
 *
 * When fieldName is empty or produces an empty slug after sanitise_key(),
 * falls back to wp_unique_id() so that every field on the page has a
 * unique id attribute — preventing label-for mismatches on fields 2-N.
 *
 * @param string $field_name Field name attribute (may be empty).
 * @return string Field ID (sgs-field-{slug} or sgs-field-{unique}).
 */
function field_id( string $field_name ): string {
	$slug = sanitize_key( $field_name );

	if ( '' === $slug ) {
		// No fieldName set — generate a unique, page-scoped ID so that each
		// unconfigured field still gets its own id and matching label for="".
		return wp_unique_id( 'sgs-field-' );
	}

	return 'sgs-field-' . $slug;
}

/**
 * Build input attributes string.
 *
 * Generates all common input attributes (id, name, placeholder,
 * required, aria-describedby) for use in text/email/number fields.
 *
 * Always wires aria-describedby to the error element (and help text when present)
 * so that screen readers announce inline validation messages.
 *
 * @param string $field_id   Field ID (from field_id()).
 * @param array  $attributes Block attributes.
 * @param bool   $with_value Print the default value as a value attribute (false for textarea and select,
 *                           which carry it in their content).
 * @return string Space-separated attribute string.
 */
function field_input_attrs( string $field_id, array $attributes, bool $with_value = true ): string {
	$field_name  = $attributes['fieldName'] ?? '';
	$placeholder = $attributes['placeholder'] ?? '';
	$required    = ! empty( $attributes['required'] );
	$help_text   = $attributes['helpText'] ?? '';

	// Derive the submission key from fieldName when set, otherwise fall back to
	// the field_id value (which is already unique per page) so that name="" is
	// never empty — an empty name means the field is silently excluded from POST.
	$field_slug = sanitize_key( $field_name );
	if ( '' === $field_slug ) {
		// field_id() prefixes with 'sgs-field-'; strip it to get the raw slug.
		$field_slug = preg_replace( '/^sgs-field-/', '', $field_id );
	}
	$submission_name = 'sgs-field-' . $field_slug;

	$attrs = array(
		'id="' . esc_attr( $field_id ) . '"',
		'name="' . esc_attr( $submission_name ) . '"',
	);

	if ( ! empty( $placeholder ) ) {
		$attrs[] = 'placeholder="' . esc_attr( $placeholder ) . '"';
	} else {
		// Fallback empty space placeholder to enable CSS floating labels pattern via :not(:placeholder-shown).
		$attrs[] = 'placeholder=" "';
	}

	if ( $required ) {
		$attrs[] = 'required';
		$attrs[] = 'aria-required="true"';
	}

	// Always include the error element ID in aria-describedby so that screen readers
	// announce inline validation messages when the field becomes invalid.
	$described_by = array( esc_attr( $field_id ) . '-error' );
	if ( ! empty( $help_text ) ) {
		$described_by[] = esc_attr( $field_id ) . '-help';
	}
	$attrs[] = 'aria-describedby="' . implode( ' ', $described_by ) . '"';

	$attrs = array_merge( $attrs, field_feature_attrs( $attributes ) );

	if ( $with_value ) {
		$default = field_default_value( $attributes );
		if ( '' !== $default ) {
			$attrs[] = 'value="' . esc_attr( $default ) . '"';
		}
	}

	return implode( ' ', $attrs );
}

/**
 * Render an inline error message placeholder for a field.
 *
 * The element is visually hidden when empty and populated by client-side
 * validation. Screen readers pick it up via aria-describedby on the input.
 *
 * @param string $field_id Field ID (from field_id()).
 * @return string Error span HTML.
 */
function field_error( string $field_id ): string {
	return sprintf(
		'<span id="%s-error" class="sgs-form-field__error" role="alert" aria-live="polite"></span>',
		esc_attr( $field_id )
	);
}

/**
 * The inputmode values a field may declare (HTML virtual-keyboard hint). Anything else renders nothing.
 *
 * @return string[] Allowed values.
 */
function field_inputmodes(): array {
	return array( 'none', 'text', 'decimal', 'numeric', 'tel', 'search', 'email', 'url' );
}

/**
 * Clean a free-text setting: no tags, no control characters, cut to a length. Empty when nothing is left.
 *
 * @param mixed $value  Raw attribute value.
 * @param int   $length    Maximum characters.
 * @param bool  $multiline Keep line breaks (a textarea's default).
 * @return string Clean text.
 */
function field_clean_text( $value, int $length = 200, bool $multiline = false ): string {
	if ( ! is_string( $value ) ) {
		return '';
	}
	$clean = trim( $multiline ? sanitize_textarea_field( $value ) : sanitize_text_field( $value ) );
	return function_exists( 'mb_substr' ) ? mb_substr( $clean, 0, $length ) : substr( $clean, 0, $length );
}

/**
 * The autocomplete attribute value (Spec 04 FR-4-6): an HTML autofill token list, either one of the standard
 * tokens or a custom value. Only lower-case letters, digits, hyphens and single spaces pass; anything else
 * renders nothing.
 *
 * @param array $attributes Block attributes.
 * @return string Token list, or '' when unset or not valid.
 */
function field_autocomplete_value( array $attributes ): string {
	$value = strtolower( trim( (string) ( $attributes['autocomplete'] ?? '' ) ) );
	return 1 === preg_match( '/^[a-z0-9]+(?:[- ][a-z0-9]+)*$/', $value ) && strlen( $value ) <= 120 ? $value : '';
}

/**
 * The URL query parameter name a field takes its value from (Spec 04 FR-4-8). The browser applies it; the
 * server never reads the query string, so a cached page stays correct for every visitor.
 *
 * @param array $attributes Block attributes.
 * @return string Parameter name, or '' when unset.
 */
function field_value_param( array $attributes ): string {
	$name = preg_replace( '/[^A-Za-z0-9_\-]/', '', (string) ( $attributes['valueFromParam'] ?? '' ) );
	return substr( (string) $name, 0, 64 );
}

/**
 * The data-sgs-value-param attribute for a field, or '' when it takes no value from the link.
 *
 * @param array $attributes Block attributes.
 * @return string Attribute string (no leading space).
 */
function field_value_param_attr( array $attributes ): string {
	$name = field_value_param( $attributes );
	return '' === $name ? '' : 'data-sgs-value-param="' . esc_attr( $name ) . '"';
}

/**
 * Per-field validation copy as data attributes (Spec 04 FR-4-3): data-sgs-msg-required,
 * data-sgs-msg-invalid and data-sgs-msg-toolong. The form runtime reads them when it shows an error.
 *
 * @param array $attributes Block attributes (msgRequired, msgInvalid, msgTooLong).
 * @return string[] Attribute strings, empty when no copy is set.
 */
function field_message_attrs( array $attributes ): array {
	$out = array();
	foreach ( array(
		'msgRequired' => 'data-sgs-msg-required',
		'msgInvalid'  => 'data-sgs-msg-invalid',
		'msgTooLong'  => 'data-sgs-msg-toolong',
	) as $key => $attr ) {
		$text = field_clean_text( $attributes[ $key ] ?? '' );
		if ( '' !== $text ) {
			$out[] = $attr . '="' . esc_attr( $text ) . '"';
		}
	}
	return $out;
}

/**
 * The feature attributes shared by every text-like input (Spec 04 FR-4-3, 4-5, 4-6, 4-7, 4-8): autocomplete,
 * inputmode, maxlength, validation copy and the link-parameter name. A block that does not declare a setting
 * has no such attribute, so nothing prints for it.
 *
 * @param array $attributes Block attributes.
 * @return string[] Attribute strings.
 */
function field_feature_attrs( array $attributes ): array {
	$out = array();

	$autocomplete = field_autocomplete_value( $attributes );
	if ( '' !== $autocomplete ) {
		$out[] = 'autocomplete="' . esc_attr( $autocomplete ) . '"';
	}

	$inputmode = (string) ( $attributes['inputmode'] ?? '' );
	if ( in_array( $inputmode, field_inputmodes(), true ) ) {
		$out[] = 'inputmode="' . esc_attr( $inputmode ) . '"';
	}

	$max = absint( $attributes['maxLength'] ?? 0 );
	if ( $max > 0 ) {
		$out[] = 'maxlength="' . min( $max, 100000 ) . '"';
	}

	$out = array_merge( $out, field_message_attrs( $attributes ) );

	$param = field_value_param_attr( $attributes );
	if ( '' !== $param ) {
		$out[] = $param;
	}

	return $out;
}

/**
 * A text-like field's default value (Spec 04 FR-4-8), cleaned and cut to 2000 characters.
 *
 * @param array $attributes Block attributes.
 * @param bool  $multiline  Keep line breaks (textarea).
 * @return string Default value, or ''.
 */
function field_default_value( array $attributes, bool $multiline = false ): string {
	return field_clean_text( $attributes['defaultValue'] ?? '', 2000, $multiline );
}

/**
 * A select's default value (Spec 04 FR-4-8): kept only when it is one of the select's own option values.
 *
 * @param array    $attributes Block attributes.
 * @param string[] $values     The option values the select renders.
 * @return string The default, or '' when unset or not an option.
 */
function field_select_default( array $attributes, array $values ): string {
	$default = (string) ( $attributes['defaultValue'] ?? '' );
	return '' !== $default && in_array( $default, array_map( 'strval', $values ), true ) ? $default : '';
}

/**
 * The live character counter under a textarea (Spec 04 FR-4-5). Printed only when a maximum length is set and
 * the counter is on. The textarea's view module keeps the count current.
 *
 * @param string $field_id   Field ID (from field_id()).
 * @param array  $attributes Block attributes (maxLength, showCounter, defaultValue).
 * @return string Counter HTML, or '' when there is none.
 */
function field_counter( string $field_id, array $attributes ): string {
	$max = min( absint( $attributes['maxLength'] ?? 0 ), 100000 );
	if ( $max < 1 || false === ( $attributes['showCounter'] ?? true ) ) {
		return '';
	}
	$default = field_default_value( $attributes, true );
	$start   = function_exists( 'mb_strlen' ) ? mb_strlen( $default ) : strlen( $default );
	return sprintf(
		'<span class="sgs-form-field__counter" aria-live="polite" data-sgs-counter-for="%s" data-sgs-counter-max="%d">%d / %d</span>',
		esc_attr( $field_id ),
		$max,
		min( $start, $max ),
		$max
	);
}
